import React, { useState } from 'react';
import {
  Wrench,
  CheckSquare,
  Square,
  Copy,
  Check,
  FileText,
  AlertCircle,
  HelpCircle,
  BookOpen,
  ArrowRight,
  ShieldCheck,
  ExternalLink,
  ChevronRight
} from 'lucide-react';
import { Language, DiagnosticIssue, SOPDocument } from '../types';
import { translations } from '../translations';
import { mockDiagnosticIssues, mockSops } from '../data/mockData';

interface DiagnosticWizardProps {
  currentLang: Language;
  onOpenSopModal: (title: string, content: string) => void;
  onAskAi: (prompt: string) => void;
}

export const DiagnosticWizard: React.FC<DiagnosticWizardProps> = ({
  currentLang,
  onOpenSopModal,
  onAskAi,
}) => {
  const t = translations[currentLang];
  const [subTab, setSubTab] = useState<'wizard' | 'sops'>('wizard');
  const [selectedIssue, setSelectedIssue] = useState<DiagnosticIssue>(mockDiagnosticIssues[0]);
  const [completedSteps, setCompletedSteps] = useState<Record<string, boolean>>({});
  const [copied, setCopied] = useState(false);

  const toggleStep = (stepId: string) => {
    setCompletedSteps((prev) => ({
      ...prev,
      [stepId]: !prev[stepId],
    }));
  };

  const handleSelectIssue = (issue: DiagnosticIssue) => {
    setSelectedIssue(issue);
    setCompletedSteps({});
  };

  const verifiedCount = selectedIssue.steps.filter((s) => completedSteps[s.id]).length;
  const progressPercent = Math.round((verifiedCount / selectedIssue.steps.length) * 100);

  const copyDiagnosticLog = () => {
    const text = `E2 SOLUTIONS DIAGNOSTIC RESOLUTION LOG
Issue: ${selectedIssue.title}
Code: ${selectedIssue.commonErrorCode}
Policy Ref: ${selectedIssue.policyRef}
Progress: ${verifiedCount}/${selectedIssue.steps.length} Steps Satisfied (${progressPercent}%)

Steps Completed:
${selectedIssue.steps.map((s) => `[${completedSteps[s.id] ? 'X' : ' '}] ${s.title}: ${s.description}`).join('\n')}

Generated by E2 Mission Support Console - Tier-1 Operations`;

    navigator.clipboard.writeText(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="space-y-6">
      {/* Top Header Card */}
      <div className="bg-slate-900 border border-slate-800 rounded-xl p-5 shadow-lg">
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
          <div className="flex items-center space-x-3">
            <span className="p-2.5 rounded-lg bg-blue-900/40 text-blue-400 border border-blue-700/40">
              <Wrench className="w-5 h-5" />
            </span>
            <div>
              <h2 className="text-lg font-bold text-white">{t.diagnosticsTitle}</h2>
              <p className="text-xs text-slate-400">{t.diagnosticsDesc}</p>
            </div>
          </div>

          {/* Sub Navigation */}
          <div className="flex items-center bg-slate-950 p-1 rounded-lg border border-slate-800 text-xs">
            <button
              onClick={() => setSubTab('wizard')}
              className={`flex items-center space-x-1.5 px-3 py-1.5 rounded font-medium transition ${
                subTab === 'wizard'
                  ? 'bg-blue-600 text-white font-semibold shadow-sm'
                  : 'text-slate-400 hover:text-white'
              }`}
            >
              <Wrench className="w-3.5 h-3.5" />
              <span>Diagnostic Checklist</span>
            </button>
            <button
              onClick={() => setSubTab('sops')}
              className={`flex items-center space-x-1.5 px-3 py-1.5 rounded font-medium transition ${
                subTab === 'sops'
                  ? 'bg-blue-600 text-white font-semibold shadow-sm'
                  : 'text-slate-400 hover:text-white'
              }`}
            >
              <BookOpen className="w-3.5 h-3.5" />
              <span>Official SOP Library</span>
            </button>
          </div>
        </div>
      </div>

      {subTab === 'wizard' ? (
        <div className="grid grid-cols-1 lg:grid-cols-3 gap-6">
          {/* Issue Selector Column */}
          <div className="bg-slate-900 border border-slate-800 rounded-xl p-4 shadow-lg space-y-3">
            <h3 className="text-xs font-bold text-slate-400 uppercase tracking-wider">
              Common Technical Scenarios
            </h3>

            <div className="space-y-2">
              {mockDiagnosticIssues.map((issue) => {
                const isSelected = selectedIssue.id === issue.id;
                return (
                  <button
                    key={issue.id}
                    onClick={() => handleSelectIssue(issue)}
                    className={`w-full text-left p-3 rounded-lg border transition ${
                      isSelected
                        ? 'bg-blue-950/80 border-blue-500 shadow-md ring-1 ring-blue-500'
                        : 'bg-slate-950/70 border-slate-800 hover:border-slate-700'
                    }`}
                  >
                    <div className="flex items-center justify-between mb-1">
                      <span className="font-mono text-[10px] text-blue-400 font-semibold">
                        {issue.commonErrorCode}
                      </span>
                      <span className="text-[10px] text-slate-500 uppercase">{issue.category}</span>
                    </div>
                    <div className="font-semibold text-white text-xs leading-snug">{issue.title}</div>
                  </button>
                );
              })}
            </div>

            <div className="pt-3 border-t border-slate-800">
              <button
                onClick={() =>
                  onAskAi(`ต้องการให้ช่วยวิเคราะห์เคสเพิ่มเติมเกี่ยวกับ ${selectedIssue.title} ในเชิงลึก`)
                }
                className="w-full flex items-center justify-center space-x-1.5 bg-slate-800 hover:bg-slate-700 text-slate-200 text-xs py-2 rounded-lg transition"
              >
                <span>Ask AI Specialist about this</span>
                <ArrowRight className="w-3.5 h-3.5" />
              </button>
            </div>
          </div>

          {/* Interactive Checklist & Action Plan Column */}
          <div className="lg:col-span-2 bg-slate-900 border border-slate-800 rounded-xl p-5 shadow-lg space-y-5">
            <div>
              <div className="flex items-center justify-between">
                <span className="font-mono text-xs text-blue-400 font-bold bg-blue-950/60 px-2 py-0.5 rounded border border-blue-800/40">
                  {selectedIssue.commonErrorCode}
                </span>
                <span className="text-xs text-slate-400 font-mono">
                  Standard: <span className="text-slate-200">{selectedIssue.policyRef}</span>
                </span>
              </div>
              <h3 className="text-base font-bold text-white mt-1.5">{selectedIssue.title}</h3>
              <p className="text-xs text-slate-400 mt-1">{selectedIssue.summary}</p>
            </div>

            {/* Progress indicator */}
            <div className="bg-slate-950 p-3.5 rounded-lg border border-slate-800">
              <div className="flex items-center justify-between text-xs mb-1.5">
                <span className="font-semibold text-slate-300">
                  Diagnostic Verification Progress: {verifiedCount} of {selectedIssue.steps.length} Steps
                </span>
                <span className="font-mono font-bold text-blue-400">{progressPercent}%</span>
              </div>
              <div className="w-full bg-slate-800 rounded-full h-2 overflow-hidden">
                <div
                  className="bg-blue-600 h-2 rounded-full transition-all duration-300"
                  style={{ width: `${progressPercent}%` }}
                />
              </div>
            </div>

            {/* Step by step interactive list */}
            <div className="space-y-3">
              <h4 className="text-xs font-bold text-slate-300 uppercase tracking-wider">
                {t.stepVerification}
              </h4>

              {selectedIssue.steps.map((step, idx) => {
                const isChecked = !!completedSteps[step.id];
                return (
                  <div
                    key={step.id}
                    onClick={() => toggleStep(step.id)}
                    className={`cursor-pointer p-4 rounded-lg border transition ${
                      isChecked
                        ? 'bg-emerald-950/20 border-emerald-700/50'
                        : 'bg-slate-950/80 border-slate-800 hover:border-slate-700'
                    }`}
                  >
                    <div className="flex items-start space-x-3">
                      <div className="mt-0.5 text-blue-400">
                        {isChecked ? (
                          <CheckSquare className="w-5 h-5 text-emerald-400" />
                        ) : (
                          <Square className="w-5 h-5 text-slate-500" />
                        )}
                      </div>

                      <div className="flex-1">
                        <div className="flex items-center space-x-2">
                          <span className={`font-semibold text-xs sm:text-sm ${isChecked ? 'text-emerald-300 line-through' : 'text-white'}`}>
                            {step.title}
                          </span>
                        </div>
                        <p className="text-xs text-slate-400 mt-1">{step.description}</p>

                        <div className="mt-2.5 grid grid-cols-1 sm:grid-cols-2 gap-2 text-[11px]">
                          <div className="bg-slate-900/90 p-2 rounded border border-slate-800 text-slate-300">
                            <span className="text-blue-400 font-semibold block">Action Required:</span>
                            {step.actionRequired}
                          </div>
                          <div className="bg-slate-900/90 p-2 rounded border border-slate-800 text-slate-300">
                            <span className="text-amber-400 font-semibold block">If Check Fails:</span>
                            {step.resolutionIfFailed}
                          </div>
                        </div>
                      </div>
                    </div>
                  </div>
                );
              })}
            </div>

            {/* Bottom Actions */}
            <div className="pt-4 border-t border-slate-800 flex flex-wrap items-center justify-between gap-3">
              <button
                onClick={copyDiagnosticLog}
                className="flex items-center space-x-1.5 bg-slate-800 hover:bg-slate-700 text-slate-200 text-xs px-3.5 py-2 rounded-lg font-medium transition"
              >
                {copied ? (
                  <>
                    <Check className="w-3.5 h-3.5 text-emerald-400" />
                    <span className="text-emerald-400">Resolution Log Copied</span>
                  </>
                ) : (
                  <>
                    <Copy className="w-3.5 h-3.5" />
                    <span>{t.copyResolution}</span>
                  </>
                )}
              </button>

              <button
                onClick={() =>
                  onOpenSopModal(
                    `Standard Operating Procedure: ${selectedIssue.title}`,
                    `### SOP Document: ${selectedIssue.commonErrorCode}\n\n**Topic:** ${selectedIssue.title}\n**Policy Standard:** ${selectedIssue.policyRef}\n\n#### Diagnostic Workflow Checklist\n${selectedIssue.steps
                      .map((s) => `- **${s.title}**: ${s.description}\n  - *Action:* ${s.actionRequired}\n  - *Remediation:* ${s.resolutionIfFailed}`)
                      .join('\n\n')}`
                  )
                }
                className="flex items-center space-x-1.5 bg-blue-600 hover:bg-blue-500 text-white text-xs px-4 py-2 rounded-lg font-semibold transition shadow-sm"
              >
                <FileText className="w-3.5 h-3.5" />
                <span>{t.generateSopDoc}</span>
              </button>
            </div>
          </div>
        </div>
      ) : (
        /* Standard Operating Procedures Library Tab */
        <div className="grid grid-cols-1 md:grid-cols-3 gap-6">
          {mockSops.map((sop) => (
            <div
              key={sop.id}
              className="bg-slate-900 border border-slate-800 rounded-xl p-5 shadow-lg flex flex-col justify-between"
            >
              <div>
                <div className="flex items-center justify-between mb-2">
                  <span className="font-mono text-xs font-bold text-blue-400 bg-blue-950/70 px-2 py-0.5 rounded border border-blue-800/40">
                    {sop.code}
                  </span>
                  <span className="text-[10px] text-slate-500 uppercase">{sop.category}</span>
                </div>
                <h3 className="font-bold text-white text-sm mb-2 leading-snug">{sop.title}</h3>
                <p className="text-[11px] text-slate-400 mb-4">
                  Compliant with: <span className="text-slate-300 font-mono">{sop.complianceRef}</span>
                </p>
              </div>

              <div className="pt-3 border-t border-slate-800 flex items-center justify-between">
                <button
                  onClick={() => onOpenSopModal(sop.title, sop.content)}
                  className="flex items-center space-x-1 text-blue-400 hover:text-blue-300 text-xs font-semibold"
                >
                  <span>View Official SOP</span>
                  <ChevronRight className="w-3.5 h-3.5" />
                </button>

                <button
                  onClick={() => onAskAi(`ขออธิบายขั้นตอนปฏิบัติงานตามเอกสาร ${sop.code} (${sop.title}) ให้เข้าใจง่ายสำหรับแอดมิน`)}
                  className="text-[11px] text-slate-400 hover:text-white"
                >
                  Consult AI
                </button>
              </div>
            </div>
          ))}
        </div>
      )}
    </div>
  );
};
